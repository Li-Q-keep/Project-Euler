"""
Project Euler Problem 15: Lattice Paths (网格路径)
====================================================
问题描述：
    从一个 20×20 网格的左上角出发，若只允许向右或向下移动，
    则抵达右下角共有多少条不同的路径？

数学本质：
    从左上到右下必须恰好走 n 步右 + n 步下 = 2n 步。
    路径数 = 从 2n 步中选出 n 步作为"向右" = C(2n, n)。
"""

import math


# ==================== 数学公式法====================
# 思路：
#   直接利用组合数公式 C(2n, n) = (2n)! / (n! × n!)。
#
# 时间复杂度：O(n)   空间复杂度：O(1)
# 优点：最快、最简洁、最符合问题本质。
# ================================================================

def solve_math(n=20):
    """数学公式法：直接计算组合数 C(2n, n)"""
    return math.factorial(2 * n) // (math.factorial(n) * math.factorial(n))


# ==================== 动态规划（二维 DP）====================
# 思路：
#   设 dp[i][j] 表示从左上角到达格子 (i, j) 的路径数。
#   由于只能向右或向下，到达 (i, j) 只能从上方 (i-1, j) 或左方 (i, j-1) 过来。
#   状态转移方程：dp[i][j] = dp[i-1][j] + dp[i][j-1]
#   边界条件：第一行和第一列都只有 1 种走法（一直向右或一直向下）。
#
# 时间复杂度：O(n²)   空间复杂度：O(n²)
# 优点：思路直观，易于理解，适合教学演示。
# ================================================================

def solve_dp_2d(n=20):
    """二维动态规划求解"""
    # 创建 (n+1) × (n+1) 的网格（20×20 网格有 21×21 个交点）
    dp = [[0] * (n + 1) for _ in range(n + 1)]
    
    # 边界条件：第一行和第一列都只有 1 种路径
    for i in range(n + 1):
        dp[i][0] = 1  # 第一列：只能向下走
        dp[0][i] = 1  # 第一行：只能向右走
    
    # 状态转移：每个格子的路径数 = 上方路径数 + 左方路径数
    for i in range(1, n + 1):
        for j in range(1, n + 1):
            dp[i][j] = dp[i - 1][j] + dp[i][j - 1]
    
    return dp[n][n]


# ==================== 空间优化的动态规划（一维 DP）====================
# 思路：
#   观察二维 DP 的转移方程 dp[i][j] = dp[i-1][j] + dp[i][j-1]，
#   发现计算第 i 行时，只需要第 i-1 行（上方）和当前行已算出的左方值。
#   因此可以用一维数组滚动更新：
#       dp[j] = dp[j]（原值，代表上方）+ dp[j-1]（已更新，代表左方）
#
# 时间复杂度：O(n²)   空间复杂度：O(n)
# 优点：空间从 O(n²) 优化到 O(n)。
# ===========================================================================

def solve_dp_1d(n=20):
    """一维动态规划（滚动数组）求解"""
    dp = [1] * (n + 1)  # 初始化第一行全为 1
    
    for i in range(1, n + 1):
        for j in range(1, n + 1):
            # dp[j] 原值 = 从上方来的路径数
            # dp[j-1] 新值 = 从左方来的路径数
            dp[j] = dp[j] + dp[j - 1]
    
    return dp[n]


